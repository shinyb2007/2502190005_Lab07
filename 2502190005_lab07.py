def parse_line(line):
    """Take one raw line and return code, family and diameter."""
    code, dia = line.split(",")
    code = code.strip().upper()
    family = code.split("-")[1]
    return code, family, float(dia)
class Shaft:
    """Represent a shaft and its inspection results."""

    def __init__(self, code, dia):
        self.code = code
        self.dia = dia

    def deviation(self):
        """Return deviation from the target diameter of 25.00 mm."""
        return self.dia - 25.00

    def verdict(self):
        """Return ACCEPT, OVERSIZE or UNDERSIZE."""
        if self.dia > 25.05:
            return "OVERSIZE"
        elif self.dia < 24.95:
            return "UNDERSIZE"
        else:
            return "ACCEPT"
s1 = Shaft("TEST-001", 25.00)
s2 = Shaft("TEST-002", 25.08)
s3 = Shaft("TEST-003", 24.90)

print(s1.code, s1.verdict(), f"{s1.deviation():.2f}")
print(s2.code, s2.verdict(), f"{s2.deviation():.2f}")
print(s3.code, s3.verdict(), f"{s3.deviation():.2f}")

