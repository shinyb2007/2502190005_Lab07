class Batch:
    """Represent a batch containing multiple Shaft objects."""

    def __init__(self, batch_no):
        self.batch_no = batch_no
        self.parts = []

    def add(self, part):
        """Add a Shaft object to the batch."""
        self.parts.append(part)

    def acceptance_pct(self):
        """Return the percentage of accepted parts."""
        if len(self.parts) == 0:
            return 0

        accepted = 0

        for part in self.parts:
            if part.verdict() == "ACCEPT":
                accepted += 1

        return (accepted / len(self.parts)) * 100

    def worst(self):
        """Return the part object with the largest absolute deviation."""
        if len(self.parts) == 0:
            return None

        return max(self.parts, key=lambda p: abs(p.deviation()))
